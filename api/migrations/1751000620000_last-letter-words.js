/** The games' key: lower case, NFC, letters only, marks kept (letterKey in @kurda/shared). */
const letterKey = (word) => word.toLowerCase().normalize('NFC').replace(/[^\p{L}]/gu, '');
/** The dictionary's lookup key: the marks folded away (dictionaryKey in @kurda/shared). */
const folded = (word) => letterKey(word.replace(/[êîûçş]/g, (c) => ({ ê: 'e', î: 'i', û: 'u', ç: 'c', ş: 's' })[c]));
const quote = (text) => `'${text.replace(/'/g, "''")}'`;

function values() {
  const seen = new Set();
  const rows = [];
  for (const [word, pos, en] of [...TAUGHT, ...UNTAUGHT]) {
    const norm = letterKey(word);
    if (seen.has(norm)) continue;
    seen.add(norm);
    rows.push(`(${quote(word)}, ${quote(norm)}, ${quote(folded(word))}, ${Array.from(norm).length}, ${quote(pos)}, ${quote(en)})`);
  }
  return rows.join(',\n    ');
}

